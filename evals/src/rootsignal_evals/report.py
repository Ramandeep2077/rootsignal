"""Turns recorded runs into evals/EVALS.md. Every number in the report is computed from the JSONL records."""

from __future__ import annotations

import statistics
from collections import defaultdict
from collections.abc import Callable, Sequence
from typing import Any

PROFILE_LABELS = {
    "routed": "Routed: qwen2.5:1.5b triage, qwen2.5:7b investigation + remediation",
    "small_only": "Small only: qwen2.5:1.5b everywhere",
    "large_only": "Large only: qwen2.5:7b everywhere",
    "heuristic": "Rules only, no LLM (optimistic keyword baseline; see caveats)",
}


def _mean(values: Sequence[float]) -> float | None:
    values = [v for v in values if v is not None]
    return statistics.fmean(values) if values else None


def _pct(values: Sequence[Any]) -> float | None:
    values = [v for v in values if v is not None]
    return 100.0 * sum(bool(v) for v in values) / len(values) if values else None


def _quantile(values: Sequence[float], q: float) -> float | None:
    values = sorted(v for v in values if v is not None)
    if not values:
        return None
    if len(values) == 1:
        return values[0]
    return statistics.quantiles(values, n=100, method="inclusive")[round(q * 100) - 1]


def fmt(value: Any, kind: str = "num", digits: int = 1) -> str:
    if value is None:
        return "TBD"
    if kind == "pct":
        return f"{value:.{digits}f}%"
    if kind == "s":
        return f"{value:.0f} s" if value >= 10 else f"{value:.1f} s"
    if kind == "usd":
        return f"${value:.4f}" if value else "$0.00"
    if kind == "int":
        return f"{value:,.0f}"
    return f"{value:.{digits}f}"


def summarize(records: list[dict[str, Any]]) -> dict[str, Any]:
    analysed = [r for r in records if r.get("analysed")]
    raw = sum(r["raw_alerts"] for r in records)
    incidents = sum(r["incidents_created"] for r in records)
    tts = [r.get("time_to_summary_s") for r in analysed]
    return {
        "runs": len(records),
        "analysed": len(analysed),
        "timed_out": sum(bool(r.get("timed_out")) for r in records),
        "category_acc": _pct([r.get("category_correct") for r in records]),
        "service_acc": _pct([r.get("service_correct") for r in records]),
        "action_acc": _pct([r.get("action_correct") for r in records]),
        "runbook_acc": _pct([r.get("runbook_correct") for r in records]),
        "judge_mean": _mean([r.get("judge_score") for r in records]),
        "judge_correct": _pct([r.get("judge_correct") for r in records if r.get("judge_score") is not None]),
        "raw_alerts": raw,
        "incidents": incidents,
        "noise_reduction": 100.0 * (1 - incidents / raw) if raw else None,
        "grouping_recall": _mean([r.get("grouping_recall") for r in records]),
        "grouping_precision": _mean([r.get("grouping_precision") for r in records]),
        "noise_absorbed": sum(bool(r.get("noise_absorbed")) for r in records),
        "tts_mean": _mean(tts),
        "tts_p50": _quantile(tts, 0.5),
        "tts_p95": _quantile(tts, 0.95),
        "ttn_mean": _mean([r.get("time_to_notification_s") for r in analysed]),
        "tokens_mean": _mean([r.get("total_tokens") for r in analysed]),
        "llm_calls_mean": _mean([r.get("llm_calls") for r in analysed]),
        "tool_calls_mean": _mean([r.get("tool_calls") for r in analysed]),
        "failed_llm_calls": sum(r.get("failed_llm_calls") or 0 for r in records),
        "cost_mean": _mean([r.get("cost_usd") for r in analysed]),
        "unsafe_pending": sum(bool(r.get("unsafe_pending_approval")) for r in records),
        "notified": _pct([r.get("notified") for r in analysed]),
    }


def _table(headers: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def _by(
    records: list[dict[str, Any]], key: Callable[[dict[str, Any]], str]
) -> dict[str, list[dict[str, Any]]]:
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        groups[key(record)].append(record)
    return dict(groups)


def render(
    records: list[dict[str, Any]],
    guardrails: dict[str, Any] | None,
    env: dict[str, Any],
    headline_profile: str = "routed",
) -> str:
    profiles = _by(records, lambda r: r["profile"])
    order = [p for p in ("routed", "large_only", "small_only", "heuristic") if p in profiles]
    order += [p for p in profiles if p not in order]
    headline = headline_profile if headline_profile in profiles else (order[0] if order else None)
    out = ["# Evaluation results", ""]
    out.append(
        f"_Generated by `make eval` (`python -m rootsignal_evals.run`) on {env.get('date', 'TBD')}. "
        "Every number below is computed from the recorded runs in "
        f"`{env.get('results_file', 'evals/results/*.jsonl')}`; nothing is hand-entered._"
    )
    out.append("")

    if headline:
        s = summarize(profiles[headline])
        out += [
            f"## Headline: `{headline}` profile",
            "",
            f"{PROFILE_LABELS.get(headline, headline)}. {s['runs']} runs = 12 labelled scenarios x "
            f"{len({r['seed'] for r in profiles[headline]})} seeds.",
            "",
        ]
        out.append(
            _table(
                ["Metric", "Result"],
                [
                    ["Root-cause accuracy (exact category match)", fmt(s["category_acc"], "pct")],
                    ["Root-cause accuracy (LLM-as-judge, score >= 4 of 5)", fmt(s["judge_correct"], "pct")],
                    ["LLM-as-judge mean score (1-5)", fmt(s["judge_mean"], digits=2)],
                    ["Originating service identified", fmt(s["service_acc"], "pct")],
                    [
                        "Correct remediation proposed (runbook action, awaiting approval)",
                        fmt(s["action_acc"], "pct"),
                    ],
                    ["Correct runbook retrieved", fmt(s["runbook_acc"], "pct")],
                    [
                        "Alert noise reduction (raw alerts -> incidents)",
                        f"{fmt(s['noise_reduction'], 'pct')} ({s['raw_alerts']:,} alerts -> {s['incidents']:,} incidents)",
                    ],
                    [
                        "Grouping recall / precision (storm alerts in the main incident)",
                        f"{fmt(_scale(s['grouping_recall']), 'pct')} / {fmt(_scale(s['grouping_precision']), 'pct')}",
                    ],
                    [
                        "Time to summary: mean / p50 / p95",
                        f"{fmt(s['tts_mean'], 's')} / {fmt(s['tts_p50'], 's')} / {fmt(s['tts_p95'], 's')}",
                    ],
                    ["Time to notification (mean)", fmt(s["ttn_mean"], "s")],
                    ["Tokens per incident (mean)", fmt(s["tokens_mean"], "int")],
                    [
                        "LLM calls / MCP tool calls per incident (mean)",
                        f"{fmt(s['llm_calls_mean'])} / {fmt(s['tool_calls_mean'])}",
                    ],
                    ["Cost per incident", fmt(s["cost_mean"], "usd") + " (local open-weight models)"],
                    ["Unsafe proposals that reached human approval", str(s["unsafe_pending"])],
                ],
            )
        )
        out.append("")

    if guardrails:
        g = guardrails
        out += [
            "## Guardrails",
            "",
            "Requirement: attempts to make the agent run unsafe actions are blocked 100% of the time.",
            "",
        ]
        live = g["live_injection"]
        out.append(
            _table(
                ["Test", "Cases", "Result"],
                [
                    [
                        "Static adversarial proposals (destructive steps, unknown actions, injection text, out-of-runbook, "
                        "unknown target, low confidence)",
                        str(g["static"]["cases"]),
                        f"{g['static']['blocked']}/{g['static']['cases']} blocked ({fmt(_scale(g['static']['block_rate']), 'pct')})",
                    ],
                    [
                        "Tampered proposals at execution time (after approval)",
                        str(g["execution_tampering"]["cases"]),
                        f"{g['execution_tampering']['blocked']}/{g['execution_tampering']['cases']} blocked "
                        f"({fmt(_scale(g['execution_tampering']['block_rate']), 'pct')})",
                    ],
                    [
                        "Live prompt injection into the remediation model (poisoned runbook / log text)",
                        str(live["cases"]),
                        (
                            f"model proposed unsafe in {live['model_produced_unsafe']}; {live['unsafe_blocked']}/"
                            f"{live['model_produced_unsafe']} blocked; unsafe reaching a human: {live['unsafe_reached_human']}"
                        )
                        if live["cases"]
                        else "TBD",
                    ],
                    [
                        "Safe controls (correct runbook actions) wrongly blocked",
                        str(g["safe_controls"]["cases"]),
                        f"{g['safe_controls']['cases'] - g['safe_controls']['allowed']} "
                        f"({fmt(_scale(g['safe_controls']['false_positive_rate']), 'pct')} false positives)",
                    ],
                ],
            )
        )
        out.append("")
        if live["cases"]:
            out.append("<details><summary>Live injection cases</summary>\n")
            out.append(
                _table(
                    ["Injected instruction", "Model proposed", "Unsafe?", "Final action shown to human"],
                    [
                        [
                            d["case"].replace("|", "/"),
                            f"`{d['model_action']}`",
                            "yes" if d["model_proposal_unsafe"] else "no",
                            f"`{d['final_action']}`",
                        ]
                        for d in live["details"]
                    ],
                )
            )
            out.append("\n</details>\n")

    if len(order) > 1:
        out += ["## Model comparison", "", "Same scenarios and seeds for every profile.", ""]
        rows = []
        for profile in order:
            s = summarize(profiles[profile])
            rows.append(
                [
                    f"`{profile}`",
                    str(s["runs"]),
                    fmt(s["category_acc"], "pct"),
                    fmt(s["judge_mean"], digits=2),
                    fmt(s["service_acc"], "pct"),
                    fmt(s["action_acc"], "pct"),
                    fmt(s["tts_mean"], "s"),
                    fmt(s["tts_p95"], "s"),
                    fmt(s["tokens_mean"], "int"),
                    fmt(s["cost_mean"], "usd"),
                ]
            )
        out.append(
            _table(
                [
                    "Profile",
                    "Runs",
                    "Category acc.",
                    "Judge (1-5)",
                    "Service acc.",
                    "Action acc.",
                    "Time to summary (mean)",
                    "p95",
                    "Tokens/incident",
                    "Cost/incident",
                ],
                rows,
            )
        )
        out.append("")
        out += [f"- `{p}`: {PROFILE_LABELS.get(p, p)}" for p in order]
        out.append("")

    if headline:
        out += [f"## Per scenario (`{headline}`)", ""]
        rows = []
        for scenario, recs in sorted(_by(profiles[headline], lambda r: r["scenario"]).items()):
            s = summarize(recs)
            predicted = sorted(
                {str(r.get("predicted_category")) for r in recs if not r.get("category_correct")}
            )
            rows.append(
                [
                    f"`{scenario}`",
                    f"{sum(bool(r.get('category_correct')) for r in recs)}/{len(recs)}",
                    fmt(s["judge_mean"], digits=1),
                    f"{sum(bool(r.get('action_correct')) for r in recs)}/{len(recs)}",
                    f"{s['raw_alerts']} -> {s['incidents']}",
                    fmt(s["tts_mean"], "s"),
                    ", ".join(f"`{p}`" for p in predicted) or "-",
                ]
            )
        out.append(
            _table(
                [
                    "Scenario",
                    "Category correct",
                    "Judge",
                    "Action correct",
                    "Alerts -> incidents",
                    "Time to summary",
                    "Wrong predictions",
                ],
                rows,
            )
        )
        out.append("")
        misses = [r for r in profiles[headline] if not r.get("category_correct")]
        if misses:
            out += ["<details><summary>Misdiagnoses (judge rationale)</summary>", ""]
            out += [
                f"- `{r['scenario']}` seed {r['seed']}: predicted `{r.get('predicted_category')}` on "
                f"`{r.get('predicted_service')}` - {r.get('judge_rationale') or r.get('hypothesis') or 'no analysis'}"
                for r in misses
            ]
            out += ["", "</details>", ""]

    out += [
        "## Environment",
        "",
        _table(["", ""], [[k, f"{v}"] for k, v in env.items() if k not in ("date",)]),
        "",
    ]
    out += [
        "## Methodology and caveats",
        "",
        "- **Synthetic data.** 12 simulator scenarios with known root causes (see `docs/scenarios.md`). Each run "
        "uses a different seed, so noise, timings and red-herring changes differ between runs. Results say how "
        "the system does on these scenarios, not on real production incidents.",
        "- **Real pipeline.** Alerts go over HTTP to the Java alert service, through Kafka (Redpanda), to the "
        "agent service (run in-process by the harness so the model profile can be switched), which uses the MCP "
        "servers and local Ollama models, writes back over HTTP, and notifies the mock Slack webhook.",
        "- **Exact match** compares the predicted category with the label. **LLM-as-judge** "
        "(`qwen2.5:7b`, temperature 0, rubric in `evals/src/rootsignal_evals/judge.py`) grades the free-text "
        "hypothesis 1-5 against the ground-truth explanation. A local 7B judge is weaker than a frontier "
        "model, so treat it as a second opinion next to exact match.",
        "- **Rules-only baseline.** The heuristic investigator was written knowing the simulator's log "
        "vocabulary, so its accuracy is an optimistic upper bound for keyword matching, not a fair competitor. "
        "It's included to show the latency/cost floor and what the LLM adds beyond keywords.",
        "- **Time to summary** runs from the first alert reaching the alert service to the analysis being "
        "stored. It includes the ~6-20 s grouping window and CPU/iGPU inference on one laptop, with other "
        "workloads running.",
        "- **Action accuracy** counts a proposal as correct when it is one of the scenario's expected runbook "
        "actions. A few actions (e.g. `enable_circuit_breaker`, `scale_out`) appear in several runbooks, so an "
        "action can be acceptable even when the diagnosis is wrong; read it together with category accuracy.",
        "- **Cost** is $0 because the models run locally; token counts are reported so hosted-model cost can be "
        "estimated with any price list.",
        "",
    ]
    return "\n".join(out)


def _scale(value: float | None) -> float | None:
    return None if value is None else value * 100
